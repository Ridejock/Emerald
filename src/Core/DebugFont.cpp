f32 DebugTextLineHeight(f32 scale)
{
    return (7.0f + 2.0f) * scale;
}

void DrawDebugText(Renderer2D& renderer, const Vec2& position, std::string_view text,
                   const Vec4& color, f32 scale)
{
    if (scale <= 0.0f)
        return;
    f32 x = position.x;
    f32 y = position.y;
    const f32 advance = 6.0f * scale;
    for (const char code : text) {
        if (code == '\n') {
            x = position.x;
            y += DebugTextLineHeight(scale);
            continue;
        }
        if (code != ' ') {
            const u8* rows = FindGlyph(code);
            for (int row = 0; row < 7; ++row) {
                int col = 0;
                while (col < 5) {
                    const bool on = (rows[row] & static_cast<u8>(1u << (4 - col))) != 0;
                    if (!on) {
                        ++col;
                        continue;
                    }
                    const int start = col;
                    while (col < 5 && (rows[row] & static_cast<u8>(1u << (4 - col))) != 0)
                        ++col;
                    renderer.FillRect(
                        {x + static_cast<f32>(start) * scale, y + static_cast<f32>(row) * scale},
                        {static_cast<f32>(col - start) * scale, scale}, color);
                }
            }
        }
        x += advance;
    }
}

